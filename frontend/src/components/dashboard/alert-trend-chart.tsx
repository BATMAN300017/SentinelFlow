'use client';

import React from 'react';

interface AlertTrendChartProps {
  totalAlerts?: number;
}

export function AlertTrendChart({ totalAlerts = 157 }: AlertTrendChartProps) {
  const days = [
    { label: 'Mon', count: 18, critical: 2 },
    { label: 'Tue', count: 24, critical: 4 },
    { label: 'Wed', count: 29, critical: 3 },
    { label: 'Thu', count: 22, critical: 1 },
    { label: 'Fri', count: 35, critical: 6 },
    { label: 'Sat', count: 14, critical: 1 },
    { label: 'Sun', count: 15, critical: 2 },
  ];

  const max = Math.max(...days.map((d) => d.count));

  return (
    <div className="p-4 sm:p-5 rounded-lg border border-slate-800/80 bg-[#111722] space-y-4">
      <div className="flex items-center justify-between">
        <div>
          <h3 className="text-xs font-semibold text-slate-100 font-mono uppercase tracking-wider">
            7-Day Detection Frequency Timeline
          </h3>
          <p className="text-[11px] text-slate-400 font-mono mt-0.5">
            <span className="text-slate-200 tabular-nums">{totalAlerts}</span> total incidents generated by autonomous rules &amp; ML engines
          </p>
        </div>
        <div className="flex items-center space-x-3 text-[10px] font-mono">
          <span className="flex items-center space-x-1.5">
            <span className="w-1.5 h-1.5 rounded-full bg-amber-500" />
            <span className="text-slate-400">Medium/High</span>
          </span>
          <span className="flex items-center space-x-1.5">
            <span className="w-1.5 h-1.5 rounded-full bg-rose-500" />
            <span className="text-slate-400">Critical</span>
          </span>
        </div>
      </div>

      <div className="h-40 flex items-end justify-between gap-3 pt-6 pb-2 px-2">
        {days.map((day) => {
          const heightPct = Math.round((day.count / max) * 100);
          return (
            <div key={day.label} className="flex-1 flex flex-col items-center gap-1.5">
              <div className="w-full flex flex-col items-center justify-end h-28">
                <div
                  style={{ height: `${heightPct}%` }}
                  className="w-full max-w-[28px] rounded-t bg-amber-500/70 hover:bg-amber-400/90 relative group transition-colors"
                >
                  <span className="text-[10px] font-mono text-amber-200 opacity-0 group-hover:opacity-100 transition-opacity absolute -top-5 left-1/2 -translate-x-1/2 tabular-nums pointer-events-none">
                    {day.count}
                  </span>
                </div>
              </div>
              <span className="text-[10px] font-mono text-slate-400">{day.label}</span>
            </div>
          );
        })}
      </div>
    </div>
  );
}
